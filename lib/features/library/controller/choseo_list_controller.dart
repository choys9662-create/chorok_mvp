// ─── 상태 ────────────────────────────────────────────────────────────────────

class ChoseoListState {
  final List<IsarChoseo> items; // DB 전체 (검색 전)
  final String query;
  final bool isLoading;
  final bool isLoadingMore;
  final bool hasMore;
  final bool hasError;

  const ChoseoListState({
    required this.items,
    this.query = '',
    this.isLoading = true,
    this.isLoadingMore = false,
    this.hasMore = true,
    this.hasError = false,
  });

  /// 검색 필터 적용된 목록
  List<IsarChoseo> get filtered {
    if (query.trim().isEmpty) return items;
    final q = query.toLowerCase();
    return items.where((c) {
      return c.content.toLowerCase().contains(q) ||
          (c.myThought?.toLowerCase().contains(q) ?? false) ||
          c.bookTitle.toLowerCase().contains(q) ||
          c.bookAuthor.toLowerCase().contains(q);
    }).toList();
  }

  /// 책별 그룹 (책 제목 → 초서 목록)
  Map<String, List<IsarChoseo>> get byBook {
    final result = <String, List<IsarChoseo>>{};
    for (final c in filtered) {
      result.putIfAbsent(c.bookTitle, () => []).add(c);
    }
    return result;
  }

  ChoseoListState copyWith({
    List<IsarChoseo>? items,
    String? query,
    bool? isLoading,
    bool? isLoadingMore,
    bool? hasMore,
    bool? hasError,
  }) => ChoseoListState(
    items: items ?? this.items,
    query: query ?? this.query,
    isLoading: isLoading ?? this.isLoading,
    isLoadingMore: isLoadingMore ?? this.isLoadingMore,
    hasMore: hasMore ?? this.hasMore,
    hasError: hasError ?? this.hasError,
  );
}

// ─── Notifier ────────────────────────────────────────────────────────────────

class ChoseoListNotifier extends Notifier<ChoseoListState> {
  @override
  ChoseoListState build() {
    // 빌드 직후 로드
    Future.microtask(load);
    return const ChoseoListState(items: [], isLoading: true);
  }

  static const _pageSize = 50;

  int _aggCount(dynamic agg) => (agg is List && agg.isNotEmpty)
      ? ((agg.first as Map)['count'] as int? ?? 0)
      : 0;

  IsarChoseo _fromRow(Map<String, dynamic> r) {
    final book = r['books'] as Map<String, dynamic>?;
    return IsarChoseo(
      choseoId: r['id'] as String,
      bookId: r['book_id'] as String? ?? '',
      bookTitle: book?['title'] as String? ?? '',
      bookAuthor: book?['author'] as String? ?? '',
      content: r['content'] as String,
      myThought: r['thought'] as String?,
      pageNumber: r['page_number'] as int?,
      createdAt: DateTime.parse(r['created_at'] as String),
      likeCount: _aggCount(r['sentence_likes']),
      commentCount: _aggCount(r['sentence_comments']),
    );
  }

  /// 최초 로드 및 당겨서 새로고침 — 첫 페이지부터 다시 불러온다.
  Future<void> load() async {
    if (kUseMock) {
      state = state.copyWith(
        items: _kMockChoseo,
        isLoading: false,
        hasMore: false,
        hasError: false,
      );
      return;
    }
    state = state.copyWith(isLoading: true, hasError: false);
    try {
      final rows = await ref
          .read(dbServiceProvider)
          .fetchMySentences(limit: _pageSize);
      final items = rows.map(_fromRow).toList();
      state = state.copyWith(
        items: items,
        isLoading: false,
        hasMore: rows.length == _pageSize,
        hasError: false,
      );
    } catch (_) {
      // 로드 실패는 "기록 없음"과 구분되어야 한다 — 빈 목록으로 위장하지 않는다.
      state = state.copyWith(isLoading: false, hasError: true);
    }
  }

  /// 다음 페이지 — 마지막 항목의 createdAt보다 오래된 항목을 이어붙인다.
  Future<void> loadMore() async {
    if (kUseMock ||
        state.isLoading ||
        state.isLoadingMore ||
        !state.hasMore ||
        state.items.isEmpty) {
      return;
    }
    state = state.copyWith(isLoadingMore: true);
    try {
      final rows = await ref
          .read(dbServiceProvider)
          .fetchMySentences(
            before: state.items.last.createdAt,
            limit: _pageSize,
          );
      final more = rows.map(_fromRow).toList();
      state = state.copyWith(
        items: [...state.items, ...more],
        isLoadingMore: false,
        hasMore: rows.length == _pageSize,
      );
    } catch (_) {
      // 다음 페이지 실패는 기존 목록을 유지하고 재시도 여지만 남긴다.
      state = state.copyWith(isLoadingMore: false);
    }
  }

  void search(String query) {
    state = state.copyWith(query: query);
  }
}

final choseoListProvider =
    NotifierProvider<ChoseoListNotifier, ChoseoListState>(
      ChoseoListNotifier.new,
    );

